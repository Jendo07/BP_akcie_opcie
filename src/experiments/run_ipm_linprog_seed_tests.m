function results = run_ipm_linprog_seed_tests(firstSeed, NValues, numSeeds, parameterSets, caseTypes, makePlots, exportExcel, outputExcelFile, openExcel, printDetails)
% RUN_IPM_LINPROG_SEED_TESTS
% Finálne testovanie IPM oproti linprog pre viac hodnôt N a viac seedov.
%
% Úspešnosť testu sa vyhodnocuje podľa troch numerických kritérií:
%   1. valueOk  - rozdiel výnosov IPM a linprog je najviac epsilon,
%   2. primalOk - primárne reziduum IPM je najviac epsilon,
%   3. dualOk   - duálna medzera IPM je najviac epsilon.
%
% Dôležité:
%   Pre každú hodnotu N sa používa samostatná skupina seedov.
%   Tým sa predchádza tomu, aby trhy pre väčšie N boli iba rozšírením
%   trhov pre menšie N pri rovnakom seede.
%
% Výber aktív sa ponecháva vo výpise kvôli interpretácii portfólia,
% ale nerozhoduje o úspešnosti testu.
%
% Voliteľne sa výsledky uložia do Excel súboru.
%
% printDetails:
%   false - nevypisuje každý mini test do Command Window
%   true  - vypisuje každý mini test ako doteraz

    if nargin < 1 || isempty(firstSeed), firstSeed = 1; end
    if nargin < 2 || isempty(NValues), NValues = 5:10; end
    if nargin < 3 || isempty(numSeeds), numSeeds = 20; end

    if nargin < 4 || isempty(parameterSets)
        error('ParameterSets zadaj v main.m. Funkcia ich zámerne nemá natvrdo nastavené.');
    end

    if nargin < 5 || isempty(caseTypes), caseTypes = {'call','all'}; end
    if nargin < 6 || isempty(makePlots), makePlots = true; end
    if nargin < 7 || isempty(exportExcel), exportExcel = true; end
    if nargin < 8 || isempty(outputExcelFile), outputExcelFile = "ipm_linprog_results.xlsx"; end
    if nargin < 9 || isempty(openExcel), openExcel = true; end
    if nargin < 10 || isempty(printDetails), printDetails = false; end

    NValues = NValues(:).';
    caseTypes = string(caseTypes);
    parameterSetNames = get_parameter_set_names(parameterSets);

    totalUsedSeeds = numel(NValues) * numSeeds;
    lastSeed = firstSeed + totalUsedSeeds - 1;

    fprintf('\n============================================================\n');
    fprintf(' FINÁLNE TESTOVANIE IPM VS. LINPROG\n');
    fprintf('============================================================\n');
    fprintf('NValues = %s\n', mat2str(NValues));
    fprintf('počet seedov pre každé N = %d\n', numSeeds);
    fprintf('celkový rozsah použitých seedov = %d-%d\n', firstSeed, lastSeed);
    fprintf('Úspešnosť testu: valueOk && primalOk && dualOk.\n');
    fprintf('Hranica presnosti je epsilon z danej sady parametrov.\n');
    fprintf('Pri výbere aktív sa používa hranica váhy 1e-4.\n');
    fprintf('Váhy portfólia sa vypisujú na 4 desatinné miesta.\n');
    fprintf('Výnosy sa vypisujú v percentách na 2 desatinné miesta.\n');
    fprintf('Pre každé N sa používa samostatná skupina seedov.\n');
    fprintf('printDetails = %d\n', printDetails);

    detailTable = table();
    displayTable = table();

    for p = 1:numel(parameterSets)

        params = parameterSets(p);

        fprintf('\n------------------------------------------------------------\n');
        fprintf('SADA PARAMETROV: %s\n', string(params.name));
        fprintf('epsilon = %s, theta = %s, ksi = %s\n', ...
            fmtSci(params.epsilon), fmtTheta(params.theta), fmtSci(params.ksi));

        for nIndex = 1:numel(NValues)

            N = NValues(nIndex);

            seedStart = firstSeed + (nIndex - 1) * numSeeds;
            seedEnd = seedStart + numSeeds - 1;

            fprintf('\n  Testujem N = %d, seedy %d-%d\n', N, seedStart, seedEnd);

            for seedIndex = 1:numSeeds

                marketSeed = seedStart + seedIndex - 1;

                for caseType = caseTypes

                    try
                        r = compare_ipm_linprog_by_seed( ...
                            marketSeed, N, char(caseType), ...
                            params.epsilon, params.theta, params.ksi);

                        row = make_detail_row(r, params, marketSeed, N, caseType);

                    catch ME
                        row = make_error_row(marketSeed, N, caseType, params, ME.message);
                    end

                    outputRow = make_display_row(row);

                    detailTable = [detailTable; row]; %#ok<AGROW>
                    displayTable = [displayTable; outputRow]; %#ok<AGROW>

                    if printDetails
                        disp(outputRow);
                    end
                end
            end
        end
    end

    summaryTable = make_summary_table(detailTable);
    print_final_summary(summaryTable, caseTypes);

    if exportExcel
        export_results_to_excel(displayTable, summaryTable, outputExcelFile, openExcel);
    end

    if makePlots
        for caseType = caseTypes
            plot_case_graphs(summaryTable, caseType, parameterSetNames, numSeeds);
        end
    end

    results = struct();
    results.detailTable = detailTable;
    results.displayTable = displayTable;
    results.summaryTable = summaryTable;
    results.parameters = struct( ...
        'firstSeed', firstSeed, ...
        'lastSeed', lastSeed, ...
        'NValues', NValues, ...
        'numSeedsPerN', numSeeds, ...
        'totalUsedSeeds', totalUsedSeeds, ...
        'parameterSets', parameterSets, ...
        'caseTypes', caseTypes, ...
        'outputExcelFile', outputExcelFile, ...
        'printDetails', printDetails ...
    );

    for caseType = caseTypes
        fieldName = char(caseType);
        results.(fieldName).detailTable = detailTable(detailTable.caseType == caseType, :);
        results.(fieldName).displayTable = displayTable(displayTable.caseType == caseType, :);
        results.(fieldName).summaryTable = summaryTable(summaryTable.caseType == caseType, :);
    end
end


function row = make_detail_row(r, params, seed, N, caseType)
% MAKE_DETAIL_ROW
% Vytvorí jeden riadok detailnej tabuľky pre úspešne vyriešený test.

    epsilon = params.epsilon;
    weightTolerance = 1e-4;

    [linNames, linWeights] = selected_assets(r.xLinprog, caseType, N, weightTolerance);
    [ipmNames, ipmWeights] = selected_assets(r.xIpm, caseType, N, weightTolerance);

    valueError = abs(r.returnLinprog - r.returnIpm);
    primalResidual = r.residualIpm;
    dualGap = r.dualGapIpm;

    valueOk = valueError <= epsilon;
    primalOk = primalResidual <= epsilon;
    dualOk = dualGap <= epsilon;

    testOk = valueOk && primalOk && dualOk;

    row = table( ...
        string(params.name), ...
        params.epsilon, ...
        params.theta, ...
        params.ksi, ...
        N, ...
        seed, ...
        string(caseType), ...
        join_or_dash(linNames), ...
        join_or_dash(linWeights), ...
        join_or_dash(ipmNames), ...
        join_or_dash(ipmWeights), ...
        string(fmtPct2(r.returnLinprog)), ...
        string(fmtPct2(r.returnIpm)), ...
        r.returnLinprog, ...
        r.returnIpm, ...
        valueError, ...
        primalResidual, ...
        dualGap, ...
        r.linprogTime, ...
        r.ipmTime, ...
        valueOk, ...
        primalOk, ...
        dualOk, ...
        testOk, ...
        "OK", ...
        'VariableNames', { ...
            'parameterSet', ...
            'epsilon', ...
            'theta', ...
            'ksi', ...
            'N', ...
            'seed', ...
            'caseType', ...
            'selectedLinprog', ...
            'weightsLinprog', ...
            'selectedIpm', ...
            'weightsIpm', ...
            'returnLinprog', ...
            'returnIpm', ...
            'returnLinprogRaw', ...
            'returnIpmRaw', ...
            'valueError', ...
            'primalResidual', ...
            'dualGap', ...
            'linprogTime', ...
            'ipmTime', ...
            'valueOk', ...
            'primalOk', ...
            'dualOk', ...
            'testOk', ...
            'status' ...
        } ...
    );
end


