            'N', ...
            'totalTests', ...
            'successRate', ...
            'avgLinprogTime', ...
            'avgIpmTime', ...
            'avgReturnLinprog', ...
            'avgReturnIpm' ...
        } ...
    );
end


function plot_case_graphs(T, caseType, parameterSetNames, numSeeds)
% PLOT_CASE_GRAPHS
% Vykreslí tri grafy pre jeden prípad:
%   1. úspešnosť numerických kritérií,
%   2. porovnanie priemerných časov,
%   3. priemerný výnos podľa N.

    rows = T(T.caseType == caseType, :);
    Ns = unique(rows.N).';

    figure('Name', sprintf('Finálne výsledky - %s', upper(char(caseType))));
    tiledlayout(1, 3, 'TileSpacing', 'compact', 'Padding', 'compact');

    nexttile;
    plot_success_count(rows, Ns, parameterSetNames, numSeeds, caseType);

    nexttile;
    plot_time_comparison(rows, Ns, parameterSetNames, caseType);

    nexttile;
    plot_average_return(rows, Ns, parameterSetNames, caseType);
end


function plot_success_count(rows, Ns, parameterSetNames, numSeeds, caseType)
% PLOT_SUCCESS_COUNT
% Počet testov, ktoré splnili numerické kritériá úspešnosti.

    Y = NaN(length(Ns), length(parameterSetNames));

    for i = 1:length(Ns)
        for j = 1:length(parameterSetNames)
            idx = rows.N == Ns(i) & rows.parameterSet == parameterSetNames(j);

            if any(idx)
                Y(i, j) = rows.successRate(idx) / 100 * rows.totalTests(idx);
            end
        end
    end

    bar(Ns, Y);

    xlabel('N');
    ylabel('Počet úspešných testov');
    title(sprintf('Úspešnosť numerických kritérií - %s', upper(char(caseType))));
    legend(parameterSetNames, 'Location', 'best');
    ylim([0, numSeeds]);
    grid on;
end


function plot_time_comparison(rows, Ns, parameterSetNames, caseType)
% PLOT_TIME_COMPARISON
% Porovná priemerný čas linprog, IPM optimal a IPM worst podľa N.

    hold on;

    if length(parameterSetNames) >= 1
        optimalName = parameterSetNames(1);
        optimalTime = metric_vector(rows, Ns, optimalName, 'avgIpmTime');

        plot(Ns, optimalTime, 'go-', ...
            'LineWidth', 1.6, ...
            'MarkerSize', 7, ...
            'MarkerFaceColor', 'g', ...
            'DisplayName', 'IPM optimal');

        linprogTime = metric_vector(rows, Ns, optimalName, 'avgLinprogTime');

        plot(Ns, linprogTime, 'yo-', ...
            'LineWidth', 1.6, ...
            'MarkerSize', 7, ...
            'MarkerFaceColor', 'y', ...
            'DisplayName', 'linprog');
    end

    if length(parameterSetNames) >= 2
        worstName = parameterSetNames(2);
        worstTime = metric_vector(rows, Ns, worstName, 'avgIpmTime');

        plot(Ns, worstTime, 'ro-', ...
            'LineWidth', 1.6, ...
            'MarkerSize', 7, ...
            'MarkerFaceColor', 'r', ...
            'DisplayName', 'IPM worst');
    end

    hold off;

    xlabel('N');
    ylabel('Priemerný čas [s]');
    title(sprintf('Porovnanie priemerného času - %s', upper(char(caseType))));
    legend('Location', 'best');
    grid on;
end


function plot_average_return(rows, Ns, parameterSetNames, caseType)
% PLOT_AVERAGE_RETURN
% Vykreslí priemerný výnos podľa N.
%
% Keďže výnosy linprog, IPM optimal a IPM worst sú pri úspešnom riešení
% prakticky rovnaké, graf obsahuje iba jednu modrú čiaru.

    firstSetName = parameterSetNames(1);
    avgReturn = 100 * metric_vector(rows, Ns, firstSetName, 'avgReturnLinprog');

    plot(Ns, avgReturn, 'bo-', ...
        'LineWidth', 1.6, ...
        'MarkerSize', 7, ...
        'MarkerFaceColor', 'b');

    xlabel('N');
    ylabel('Priemerný výnos [%]');
    title(sprintf('Priemerný výnos podľa N - %s', upper(char(caseType))));
    grid on;
end


function y = metric_vector(rows, Ns, parameterSetName, metricName)
% METRIC_VECTOR
% Vráti vektor hodnôt metriky podľa N pre jednu sadu parametrov.

    y = NaN(size(Ns));

    for i = 1:length(Ns)
        idx = rows.N == Ns(i) & rows.parameterSet == parameterSetName;

        if any(idx)
            y(i) = rows.(metricName)(idx);
        end
    end
end


function [names, weights] = selected_assets(x, caseType, N, weightTolerance)
% SELECTED_ASSETS
% Vráti názvy a váhy aktív, ktorých váha je aspoň weightTolerance.

    x(abs(x) < weightTolerance) = 0;
    idx = find(abs(x) >= weightTolerance);

    names = strings(length(idx), 1);
    weights = strings(length(idx), 1);

    for i = 1:length(idx)
        names(i) = string(get_variable_name(idx(i), char(caseType), N));
        weights(i) = string(fmtWeight4(x(idx(i))));
    end
end


function names = get_parameter_set_names(parameterSets)
% GET_PARAMETER_SET_NAMES
% Vráti názvy sád parametrov ako string pole.

    names = strings(1, numel(parameterSets));

    for i = 1:numel(parameterSets)
        names(i) = string(parameterSets(i).name);
    end
end


function textValue = join_or_dash(values)
% JOIN_OR_DASH
% Spojí string hodnoty čiarkou alebo vráti pomlčku.

    if isempty(values)
        textValue = "-";
    else
        textValue = strjoin(values, ", ");
    end
end


function value = mean_omitnan(x)
% MEAN_OMITNAN
% Priemer bez NaN hodnôt.

    value = mean(x, 'omitnan');
end


function textValue = ok_text(value)
% OK_TEXT
% Prevedie logickú hodnotu na text OK / CHYBA.

    if value
        textValue = "OK";
    else
        textValue = "CHYBA";
    end
end


function textValue = fmtCriterion(value)
% FMTCRITERION
% Vypíše hodnotu kritéria v klasickom vedeckom zápise.

    if isnan(value)
        textValue = "NaN";
        return;
    end

    textValue = string(sprintf('%.3e', value));
end


function textValue = fmtWeight4(value)
% FMTWEIGHT4
% Formát váhy portfólia na 4 desatinné miesta.

    textValue = sprintf('%.4f', value);
end


function textValue = fmtPct2(value)
% FMTPCT2
% Formát výnosu v percentách na 2 desatinné miesta so slovenskou desatinnou čiarkou.

    textValue = string(sprintf('%.2f %%', 100 * value));
    textValue = strrep(textValue, '.', ',');
end


function textValue = fmt4(value)
% FMT4
% Formát čísla na 4 desatinné miesta.

    textValue = sprintf('%.4f', value);
end


function textValue = fmtSci(value)
% FMTSCI
% Formát napr. 1e-8, 1e-1.

    textValue = sprintf('%.10e', value);
    textValue = regexprep(textValue, '(\.\d*?)0+e', '$1e');
    textValue = regexprep(textValue, '\.e', 'e');
    textValue = regexprep(textValue, 'e([+-])0*(\d+)', 'e$1$2');
    textValue = strrep(textValue, 'e+', 'e');
end


function textValue = fmtTheta(value)
% FMTTHETA
% Formát napr. 0.9.

    textValue = sprintf('%.10f', value);
    textValue = regexprep(textValue, '0+$', '');
    textValue = regexprep(textValue, '\.$', '');

    if isempty(textValue)
        textValue = '0';
    end
end