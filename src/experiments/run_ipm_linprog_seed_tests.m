function summaryTable = make_summary_table(T)
% MAKE_SUMMARY_TABLE
% Vytvorí súhrnnú tabuľku podľa sady parametrov, prípadu a hodnoty N.

    [G, parameterSet, caseType, N] = findgroups(T.parameterSet, T.caseType, T.N);

    totalTests = splitapply(@numel, T.testOk, G);
    okTests = splitapply(@sum, T.testOk, G);

    summaryTable = table( ...
        parameterSet, ...
        caseType, ...
        N, ...
        totalTests, ...
        100 * okTests ./ totalTests, ...
        splitapply(@mean_omitnan, T.linprogTime, G), ...
        splitapply(@mean_omitnan, T.ipmTime, G), ...
        splitapply(@mean_omitnan, T.returnLinprogRaw, G), ...
        splitapply(@mean_omitnan, T.returnIpmRaw, G), ...
        'VariableNames', { ...
            'parameterSet', ...
            'caseType', ...
            'N', ...
            'totalTests', ...
            'successRate', ...
            'avgLinprogTime', ...
            'avgIpmTime', ...
            'avgReturnLinprog', ...
            'avgReturnIpm' ...
        } ...
    );
end


function print_final_summary(T, caseTypes)
% PRINT_FINAL_SUMMARY
% Vypíše stručný súhrn po prípadoch a sadách parametrov.

    fprintf('\n============================================================\n');
    fprintf(' SÚHRN FINÁLNEHO TESTOVANIA\n');
    fprintf('============================================================\n');
    fprintf('successRate je podiel testov, kde platí valueOk && primalOk && dualOk.\n');

    for caseType = caseTypes
        fprintf('\n------------------------------------------------------------\n');
        fprintf(' PRÍPAD: %s\n', upper(char(caseType)));
        fprintf('------------------------------------------------------------\n');

        rows = T(T.caseType == caseType, :);
        parameterSets = unique(rows.parameterSet);

        for p = 1:length(parameterSets)
            ps = parameterSets(p);
            psRows = rows(rows.parameterSet == ps, :);

            fprintf('\nSADA PARAMETROV: %s\n', ps);
            disp(psRows(:, { ...
                'N', ...
                'totalTests', ...
                'successRate', ...
                'avgLinprogTime', ...
                'avgIpmTime'}));
        end
    end
end


function export_results_to_excel(displayTable, summaryTable, outputExcelFile, openExcel)
% EXPORT_RESULTS_TO_EXCEL
% Zapíše výsledky do Excel súboru.
%
% Hárok TestResults obsahuje rovnaké stĺpce ako výpis v Command Window.
% Hárok Summary obsahuje súhrnné výsledky podľa N, prípadu a sady parametrov.
% Časy v hárku Summary sú zapísané na 4 desatinné miesta.

    outputExcelFile = string(outputExcelFile);
    summaryExcelTable = format_summary_for_excel(summaryTable);

    if isfile(outputExcelFile)
        delete(outputExcelFile);
    end

    writetable(displayTable, outputExcelFile, 'Sheet', 'TestResults');
    writetable(summaryExcelTable, outputExcelFile, 'Sheet', 'Summary');

    fprintf('\nVýsledky boli uložené do Excel súboru:\n%s\n', outputExcelFile);

    if openExcel
        try
            if ispc
                winopen(outputExcelFile);
            elseif ismac
                system(sprintf('open "%s" &', outputExcelFile));
            else
                system(sprintf('xdg-open "%s" &', outputExcelFile));
            end
        catch
            fprintf('Excel súbor sa nepodarilo automaticky otvoriť. Otvor ho manuálne z priečinka projektu.\n');
        end
    end
end


