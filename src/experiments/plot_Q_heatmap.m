function plot_Q_heatmap(Market)
    Q = Market.Q;
    N = Market.N;

    fig = figure('Name','Covariance matrix Q');

    % --- Názov hore ---
    sgtitle('Kovariančná matica Q (3N x 3N)', 'FontWeight','bold');

    % --- Heatmap ---
    imagesc(Q);
    axis image;
    colorbar;

    % Symetrický rozsah farieb okolo nuly
    maxAbs = max(abs(Q(:)));
    if maxAbs > 0
        caxis([-maxAbs, maxAbs]);
    end
    clim = caxis;

    % === ČISTÝ BLUE GRADIENT ===
    nColors = 256;
    t = linspace(0, 1, nColors).';
    R = 0.05 + 0.80 * t;
    G = 0.10 + 0.83 * t;
    B = 0.25 + 0.75 * t;
    blueMap = max(0, min(1, [R G B]));
    colormap(blueMap);

    % Osi
    xticks(1:size(Q,2));
    yticks(1:size(Q,1));
    xlim([0.5, size(Q,2)+0.5]);
    ylim([0.5, size(Q,1)+0.5]);

    % Čiary medzi blokmi
    hold on;
    xline(N + 0.5, 'k', 'LineWidth', 2);
    xline(2*N + 0.5, 'k', 'LineWidth', 2);
    yline(N + 0.5, 'k', 'LineWidth', 2);
    yline(2*N + 0.5, 'k', 'LineWidth', 2);

    % Čísla do buniek (farba podľa pozadia)
    for i = 1:size(Q,1)
        for j = 1:size(Q,2)
            val = Q(i,j);
            tn = (val - clim(1)) / (clim(2) - clim(1) + eps);

            if tn < 0.45
                txtColor = 'w';
            else
                txtColor = 'k';
            end

            text(j, i, sprintf('%.2f', val), ...
                'HorizontalAlignment','center', ...
                'FontSize',8, ...
                'Color',txtColor);
        end
    end
    hold off;

    % ===== LABELY FIXNE: dole + doľava =====
    delete(findall(fig,'Type','textboxshape'));

    ax = gca;
    ax.Units = 'normalized';
    pos = ax.Position; % [x y w h]

    total = 3*N;
    colW = pos(3) / total;
    rowH = pos(4) / total;

    % --- DOLE: Stocks / Calls / Puts ---
    labelH = 0.04;
    yBottom = pos(2) - labelH - 0.015;

    annotation(fig,'textbox', ...
        [pos(1) + colW*(0), yBottom, colW*N, labelH], ...
        'String','Stocks', ...
        'HorizontalAlignment','center', ...
        'VerticalAlignment','middle', ...
        'FontWeight','bold', ...
        'LineStyle','none');

    annotation(fig,'textbox', ...
        [pos(1) + colW*(N), yBottom, colW*N, labelH], ...
        'String','Calls', ...
        'HorizontalAlignment','center', ...
        'VerticalAlignment','middle', ...
        'FontWeight','bold', ...
        'LineStyle','none');

    annotation(fig,'textbox', ...
        [pos(1) + colW*(2*N), yBottom, colW*N, labelH], ...
        'String','Puts', ...
        'HorizontalAlignment','center', ...
        'VerticalAlignment','middle', ...
        'FontWeight','bold', ...
        'LineStyle','none');

    % --- DOĽAVA: Stocks / Calls / Puts (vertikálne) ---
    labelW = 0.055;               % šírka boxu
    xLeft = pos(1) - labelW - 0.02; % odsadenie doľava od osi (mimo heatmapy)

    % Stocks blok (hore)
    annotation(fig,'textbox', ...
        [xLeft, pos(2) + rowH*(2*N), labelW, rowH*N], ...
        'String','Stocks', ...
        'HorizontalAlignment','center', ...
        'VerticalAlignment','middle', ...
        'FontWeight','bold', ...
        'LineStyle','none', ...
        'Rotation',90);

    % Calls blok (stred)
    annotation(fig,'textbox', ...
        [xLeft, pos(2) + rowH*(N), labelW, rowH*N], ...
        'String','Calls', ...
        'HorizontalAlignment','center', ...
        'VerticalAlignment','middle', ...
        'FontWeight','bold', ...
        'LineStyle','none', ...
        'Rotation',90);

    % Puts blok (dole)
    annotation(fig,'textbox', ...
        [xLeft, pos(2) + rowH*(0), labelW, rowH*N], ...
        'String','Puts', ...
        'HorizontalAlignment','center', ...
        'VerticalAlignment','middle', ...
        'FontWeight','bold', ...
        'LineStyle','none', ...
        'Rotation',90);
end