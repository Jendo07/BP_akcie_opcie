function sample = balanced_sample_by_N(T, NValues, sampleSize, sampleSeed)
% BALANCED_SAMPLE_BY_N
% Vyberie vzorku čo najrovnomernejšie rozdelenú medzi hodnoty N.

    if isempty(T)
        sample = T;
        return;
    end

    rng(sampleSeed);

    NValues = NValues(:).';
    targetSize = min(sampleSize, height(T));

    baseQuota = floor(targetSize / numel(NValues));
    remainder = mod(targetSize, numel(NValues));

    quota = baseQuota * ones(size(NValues));
    quota(1:remainder) = quota(1:remainder) + 1;

    available = zeros(size(NValues));

    for i = 1:numel(NValues)
        available(i) = sum(T.N == NValues(i));
    end

    selectedCount = min(quota, available);
    remaining = targetSize - sum(selectedCount);

    while remaining > 0
        spare = available - selectedCount;
        [maxSpare, idx] = max(spare);

        if maxSpare <= 0
            break;
        end

        selectedCount(idx) = selectedCount(idx) + 1;
        remaining = remaining - 1;
    end

    sample = table();

    for i = 1:numel(NValues)

        N = NValues(i);
        k = selectedCount(i);

        if k <= 0
            continue;
        end

        rows = T(T.N == N, :);
        idx = randperm(height(rows), k);

        sample = [sample; rows(idx, :)]; %#ok<AGROW>
    end
end


function [putRows, noPutBalancedRows] = make_balanced_no_put_sample(detailTable, sampleSeed)
% MAKE_BALANCED_NO_PUT_SAMPLE
% Pre každé N vyberie z prípadov bez put opcie rovnaký počet riadkov,
% ako je počet prípadov s put opciou pre dané N.

    rng(sampleSeed);

    okRows = detailTable(detailTable.status == "OK", :);

    putRows = okRows(okRows.containsPut, :);
    noPutRows = okRows(~okRows.containsPut, :);

    Ns = unique(okRows.N).';
    noPutBalancedRows = table();

    for i = 1:numel(Ns)

        N = Ns(i);

        putN = putRows(putRows.N == N, :);
        noPutN = noPutRows(noPutRows.N == N, :);

        k = height(putN);

        if k == 0 || height(noPutN) == 0
            continue;
        end

        k = min(k, height(noPutN));

        idx = randperm(height(noPutN), k);
        noPutBalancedRows = [noPutBalancedRows; noPutN(idx, :)]; %#ok<AGROW>
    end
end


