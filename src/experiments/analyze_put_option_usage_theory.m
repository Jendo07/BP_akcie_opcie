function results = analyze_put_option_usage_theory(firstSeed, NValues, numSeeds, epsilon, theta, ksi, weightTolerance, sampleSize, comparisonSampleSize, makePlots, exportExcel, outputExcelFile, openExcel)
% ANALYZE_PUT_OPTION_USAGE_THEORY
% Rozšírená analýza prípadu 3: akcie + put opcie.
%
% Funkcia skúma:
%   - kedy sa v optimálnom portfóliu objaví put opcia,
%   - či výber put opcie vysvetľuje teoretický koeficient pri z_i,
%   - o koľko sa zlepší výnos oproti portfóliu iba z x_1, x_2.
%
% Grafy:
%   1. podiel portfólií s put opciou podľa N,
%   2. rozdelenie indexov vybraných put opcií pre každé N zvlášť,
%   3. porovnanie výnosu všetkých prípadov s put opciou
%      oproti výnosu portfólia iba z x_1, x_2,
%   4. vyvážené porovnanie rozdielu r_1 - r_2,
%   5. vyvážené porovnanie priemerného výnosu.
%
% Vyvážené porovnanie znamená:
%   Pre každé N sa zoberú všetky prípady s put opciou.
%   Z prípadov bez put opcie sa náhodne vyberie rovnaký počet prípadov
%   pre rovnaké N. Tým sa obmedzí skreslenie spôsobené rozdielnou veľkosťou vzoriek.

    if nargin < 1 || isempty(firstSeed), firstSeed = 1; end
    if nargin < 2 || isempty(NValues), NValues = 3:7; end
    if nargin < 3 || isempty(numSeeds), numSeeds = 200; end
    if nargin < 4 || isempty(epsilon), epsilon = 1e-8; end
    if nargin < 5 || isempty(theta), theta = 0.9; end
    if nargin < 6 || isempty(ksi), ksi = 1e-1; end
    if nargin < 7 || isempty(weightTolerance), weightTolerance = 1e-4; end
    if nargin < 8 || isempty(sampleSize), sampleSize = 50; end
    if nargin < 9 || isempty(comparisonSampleSize), comparisonSampleSize = 20; end %#ok<NASGU>
    if nargin < 10 || isempty(makePlots), makePlots = true; end
    if nargin < 11 || isempty(exportExcel), exportExcel = true; end
    if nargin < 12 || isempty(outputExcelFile), outputExcelFile = "put_option_theory_analysis.xlsx"; end
    if nargin < 13 || isempty(openExcel), openExcel = true; end

    NValues = NValues(:).';

    totalUsedSeeds = numel(NValues) * numSeeds;
    lastSeed = firstSeed + totalUsedSeeds - 1;

    fprintf('\n============================================================\n');
    fprintf(' ROZŠÍRENÁ ANALÝZA PUT OPCIÍ - TEORETICKÉ KOEFICIENTY\n');
    fprintf('============================================================\n');
    fprintf('NValues = %s\n', mat2str(NValues));
    fprintf('počet seedov pre každé N = %d\n', numSeeds);
    fprintf('celkový rozsah použitých seedov = %d-%d\n', firstSeed, lastSeed);
    fprintf('epsilon = %s, theta = %s, ksi = %s\n', fmtSci(epsilon), fmtTheta(theta), fmtSci(ksi));
    fprintf('hranica pre nenulovú váhu = %s\n', fmtSci(weightTolerance));
    fprintf('Pre každé N sa používa samostatná skupina seedov.\n');

    detailTable = table();

    for nIndex = 1:numel(NValues)

        N = NValues(nIndex);

        seedStart = firstSeed + (nIndex - 1) * numSeeds;
        seedEnd = seedStart + numSeeds - 1;

        fprintf('\n------------------------------------------------------------\n');
        fprintf('Testujem N = %d, seedy %d-%d\n', N, seedStart, seedEnd);
        fprintf('------------------------------------------------------------\n');

        for seedIndex = 1:numSeeds

            marketSeed = seedStart + seedIndex - 1;

            try
                r = compare_ipm_linprog_by_seed( ...
                    marketSeed, N, 'put', epsilon, theta, ksi);

                row = make_theory_detail_row(r, marketSeed, N, weightTolerance);

            catch ME
                row = make_error_row(marketSeed, N, ME.message);
            end

            detailTable = [detailTable; row]; %#ok<AGROW>
        end
    end

    summaryByN = make_summary_by_N(detailTable);

    okRows = detailTable(detailTable.status == "OK", :);

    withPutRows = okRows(okRows.containsPut, :);
    withoutPutRows = okRows(~okRows.containsPut, :);

    sampleWithPut = balanced_sample_by_N(withPutRows, NValues, sampleSize, 1001);
    sampleWithoutPut = balanced_sample_by_N(withoutPutRows, NValues, sampleSize, 2002);

    sampleComparison = compare_samples(sampleWithPut, sampleWithoutPut);
    sampleByNComparison = compare_samples_by_N(sampleWithPut, sampleWithoutPut, NValues);

    allPutComparison = make_all_put_comparison(withPutRows);

    [balancedPutRows, balancedNoPutRows] = make_balanced_no_put_sample(detailTable, 4004);
    balancedComparison = compare_samples(balancedPutRows, balancedNoPutRows);

    print_summary( ...
        summaryByN, ...
        sampleWithPut, ...
        sampleWithoutPut, ...
        sampleComparison, ...
        sampleByNComparison, ...
        allPutComparison, ...
        balancedPutRows, ...
        balancedNoPutRows, ...
        balancedComparison);

    if exportExcel
        export_theory_put_analysis_to_excel( ...
            detailTable, ...
            summaryByN, ...
            sampleWithPut, ...
            sampleWithoutPut, ...
            sampleComparison, ...
            sampleByNComparison, ...
            allPutComparison, ...
            balancedPutRows, ...
            balancedNoPutRows, ...
            balancedComparison, ...
            outputExcelFile, ...
            openExcel);
    end

    if makePlots
        plot_theory_put_analysis(summaryByN, detailTable, allPutComparison);
    end

    results = struct();
    results.detailTable = detailTable;
    results.summaryByN = summaryByN;
    results.sampleWithPut = sampleWithPut;
    results.sampleWithoutPut = sampleWithoutPut;
    results.sampleComparison = sampleComparison;
    results.sampleByNComparison = sampleByNComparison;
    results.allPutComparison = allPutComparison;
    results.balancedPutRows = balancedPutRows;
    results.balancedNoPutRows = balancedNoPutRows;
    results.balancedComparison = balancedComparison;

    results.parameters = struct( ...
        'firstSeed', firstSeed, ...
        'lastSeed', lastSeed, ...
        'NValues', NValues, ...
        'numSeedsPerN', numSeeds, ...
        'totalUsedSeeds', totalUsedSeeds, ...
        'epsilon', epsilon, ...
        'theta', theta, ...
        'ksi', ksi, ...
        'weightTolerance', weightTolerance, ...
        'sampleSize', sampleSize, ...
        'outputExcelFile', outputExcelFile ...
    );
end


function row = make_theory_detail_row(r, seed, N, weightTolerance)
% MAKE_THEORY_DETAIL_ROW
% Vytvorí jeden detailný riadok vrátane teoretických koeficientov.

    M = r.market;
    x = r.xLinprog(:);

    stockWeights = x(1:N);
    putWeights = x(N+1:2*N);

    [selectedNames, selectedWeights] = selected_assets(x, 'put', N, weightTolerance);

    activePutIdx = find(abs(putWeights) >= weightTolerance);
    containsPut = ~isempty(activePutIdx);
    putCount = numel(activePutIdx);
    putWeightSum = sum(abs(putWeights(activePutIdx)));

    if containsPut
        [maxPutWeight, localIdx] = max(abs(putWeights(activePutIdx)));
        selectedPutIndex = activePutIdx(localIdx);
        selectedPutName = "z_" + string(selectedPutIndex);
        selectedPutWeight = putWeights(selectedPutIndex);
        selectedPutReturn = M.puts.r(selectedPutIndex);
        selectedPutQ = M.puts.q(selectedPutIndex);
        selectedPutDelta = M.puts.delta(selectedPutIndex);
    else
        maxPutWeight = 0;
        selectedPutIndex = NaN;
        selectedPutName = "-";
        selectedPutWeight = 0;
        selectedPutReturn = NaN;
        selectedPutQ = NaN;
        selectedPutDelta = NaN;
    end

    x1Weight = stockWeights(1);
    x2Weight = stockWeights(2);

    stockReturn1 = M.stocks.r(1);
    stockReturn2 = M.stocks.r(2);
    stockReturnGap = stockReturn1 - stockReturn2;

