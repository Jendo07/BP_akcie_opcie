function coeffs = put_theory_coefficients(M)
% PUT_THEORY_COEFFICIENTS
% Vypočíta koeficienty pri put opciách z_i po dosadení x_1, x_2.

    N = M.N;

    u1 = M.stocks.u(1);
    d1 = M.stocks.d(1);
    u2 = M.stocks.u(2);
    d2 = M.stocks.d(2);

    den = u1 - d1 + d2 - u2;

    coeffs = zeros(N, 1);

    for i = 1:N
        ui = M.stocks.u(i);
        di = M.stocks.d(i);
        delta = M.puts.delta(i);

        if ui - di > 0
            coeffs(i) = (u2*d1 - u1*d2 + delta*(u2 - u1)) / den;
        else
            coeffs(i) = (u2*d1 - u1*d2 + delta*(d2 - d1)) / den;
        end
    end
end


function feasibleMaxZ = put_feasible_max_z(M)
% PUT_FEASIBLE_MAX_Z
% Pre každú put opciu z_i vypočíta maximálnu prípustnú hodnotu z_i,
% ak ponecháme aktívne iba x_1, x_2 a z_i.

    N = M.N;

    u1 = M.stocks.u(1);
    d1 = M.stocks.d(1);
    u2 = M.stocks.u(2);
    d2 = M.stocks.d(2);

    den = u1 - d1 + d2 - u2;

    x1tilde = (d2 - u2) / den;
    x2tilde = (u1 - d1) / den;

    feasibleMaxZ = inf(N, 1);

    for i = 1:N
        delta = M.puts.delta(i);

        A = (u2 - d2 - delta) / den;
        B = (delta + d1 - u1) / den;

        upperBounds = [];

        if A < 0
            upperBounds(end+1) = -x1tilde / A; %#ok<AGROW>
        end

        if B < 0
            upperBounds(end+1) = -x2tilde / B; %#ok<AGROW>
        end

        if isempty(upperBounds)
            feasibleMaxZ(i) = inf;
        else
            feasibleMaxZ(i) = max(0, min(upperBounds));
        end
    end
end


function [stockPairReturn, x1tilde, x2tilde] = stock_pair_return(M)
% STOCK_PAIR_RETURN
% Výnos portfólia zloženého iba z x_1 a x_2 v nulovo-rizikovom pomere.

    u1 = M.stocks.u(1);
    d1 = M.stocks.d(1);
    u2 = M.stocks.u(2);
    d2 = M.stocks.d(2);

    den = u1 - d1 + d2 - u2;

    x1tilde = (d2 - u2) / den;
    x2tilde = (u1 - d1) / den;

    stockPairReturn = x1tilde * M.stocks.r(1) + x2tilde * M.stocks.r(2);
end


