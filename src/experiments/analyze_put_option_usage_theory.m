        join_or_dash(selectedWeights), ...
        string(fmtPct2(r.returnLinprog)), ...
        r.returnLinprog, ...
        string(fmtPct2(stockPairReturn)), ...
        stockPairReturn, ...
        improvementVsStockPair, ...
        putCount, ...
        putWeightSum, ...
        maxPutWeight, ...
        selectedPutIndex, ...
        selectedPutName, ...
        selectedPutWeight, ...
        selectedPutReturn, ...
        selectedPutQ, ...
        selectedPutDelta, ...
        selectedPutCoeff, ...
        selectedPutFeasibleMaxZ, ...
        selectedPutPotentialGain, ...
        bestCoeffPutIndex, ...
        bestPutCoeff, ...
        bestCoeffFeasibleMaxZ, ...
        bestCoeffPotentialGain, ...
        x1Weight, ...
        x2Weight, ...
        x1Pair, ...
        x2Pair, ...
        stockReturn1, ...
        stockReturn2, ...
        stockReturnGap, ...
        "OK", ...
        'VariableNames', { ...
            'N', ...
            'seed', ...
            'containsPut', ...
            'predictedPutByCoeff', ...
            'anyPositivePutCoeff', ...
            'positivePutCoeffCount', ...
            'stockPairOnly', ...
            'selectedAssets', ...
            'selectedWeights', ...
            'returnPct', ...
            'returnValue', ...
            'stockPairReturnPct', ...
            'stockPairReturn', ...
            'improvementVsStockPair', ...
            'putCount', ...
