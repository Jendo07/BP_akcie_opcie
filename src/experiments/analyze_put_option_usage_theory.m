function plot_put_index_distribution_by_N(detailTable)
% PLOT_PUT_INDEX_DISTRIBUTION_BY_N
% Pre každé N zvlášť vykreslí čiarový graf rozdelenia indexov vybraných put opcií.

    putRows = detailTable(detailTable.containsPut & detailTable.status == "OK", :);

    figure('Name', 'Rozdelenie indexov vybraných put opcií podľa N');

    if isempty(putRows)
        text(0.1, 0.5, 'V testoch sa neobjavila žiadna put opcia.');
        axis off;
        return;
    end

    Ns = unique(detailTable.N).';
    numPlots = numel(Ns);

    numCols = 2;
    numRows = ceil(numPlots / numCols);

    tiledlayout(numRows, numCols, 'TileSpacing', 'compact', 'Padding', 'compact');

    for i = 1:numPlots

        N = Ns(i);
        rows = putRows(putRows.N == N, :);

        nexttile;

        if isempty(rows)
            text(0.15, 0.5, sprintf('N = %d\nbez výskytu put opcie', N));
            axis off;
        else
            indices = rows.selectedPutIndex;
            counts = zeros(1, N);

            for j = 1:N
                counts(j) = sum(indices == j);
            end

            plot(1:N, counts, 'bo-', ...
                'LineWidth', 1.7, ...
                'MarkerSize', 7, ...
                'MarkerFaceColor', 'b');

            xlabel('Index put opcie');
            ylabel('Počet výskytov');
            title(sprintf('N = %d', N));
            xticks(1:N);
            grid on;
        end
    end
end


function plot_all_put_vs_stock_pair(allPutComparison)
% PLOT_ALL_PUT_VS_STOCK_PAIR
% Graf porovnania výnosu všetkých prípadov s put opciou
% oproti výnosu portfólia iba z x_1, x_2.

    figure('Name', 'Porovnanie výnosu: optimum s put vs. iba x_1, x_2');

    if isempty(allPutComparison)
        text(0.1, 0.5, 'V testoch sa neobjavila žiadna put opcia.');
        axis off;
        return;
    end

    T = sortrows(allPutComparison, {'N', 'seed'});

    k = height(T);
    x = 1:k;

    putReturn = T.returnPctRaw;
    stockPairReturn = T.stockPairReturnPctRaw;

    h1 = plot(x, putReturn, 'go-', ...
        'LineWidth', 1.5, ...
        'MarkerSize', 5, ...
        'MarkerFaceColor', 'g', ...
        'DisplayName', 'optimum s put opciou');

    hold on;

    h2 = plot(x, stockPairReturn, 'bo-', ...
        'LineWidth', 1.5, ...
        'MarkerSize', 5, ...
        'MarkerFaceColor', 'b', ...
        'DisplayName', 'iba x_1, x_2');

    add_N_separators(T);

    hold off;

    xlabel('Prípady s put opciou zoradené podľa N a seedu');
    ylabel('Výnos [%]');
    title('Porovnanie výnosu všetkých prípadov s put opciou');
    legend([h1 h2], {'optimum s put opciou', 'iba x_1, x_2'}, 'Location', 'best');
    grid on;

    set_N_group_ticks(T);
end


function plot_balanced_gap_and_return_bars(detailTable)
% PLOT_BALANCED_GAP_AND_RETURN_BARS
% Vytvorí vyvážené porovnanie:
%   - všetky prípady s put opciou,
%   - rovnaký počet prípadov bez put opcie pre každé N.

    [putRows, noPutBalancedRows] = make_balanced_no_put_sample(detailTable, 4004);

    figure('Name', 'Vyvážené porovnanie prípadov s put opciou a bez put opcie');
    tiledlayout(1, 2, 'TileSpacing', 'compact', 'Padding', 'compact');

    nexttile;
    gapValues = 100 * [
        mean_or_nan(putRows.stockReturnGap), ...
        mean_or_nan(noPutBalancedRows.stockReturnGap)
    ];

    plot_two_bar_comparison( ...
        gapValues, ...
        'Priemerný rozdiel r_1 - r_2 [%]', ...
        'Vyvážené porovnanie rozdielu výnosov akcií');

    nexttile;
    returnValues = 100 * [
        mean_or_nan(putRows.returnValue), ...
        mean_or_nan(noPutBalancedRows.returnValue)
    ];

    plot_two_bar_comparison( ...
        returnValues, ...
        'Priemerný výnos [%]', ...
        'Vyvážené porovnanie priemerného výnosu');
end


function plot_two_bar_comparison(values, yLabelText, titleText)
% PLOT_TWO_BAR_COMPARISON
% Pomocná funkcia na vykreslenie dvojstĺpcového grafu.

    categories = categorical(["s put opciou", "bez put opcie"]);
    categories = reordercats(categories, ["s put opciou", "bez put opcie"]);

    bar(categories, values);

    ylabel(yLabelText);
    title(titleText);
    grid on;

    for i = 1:numel(values)
        text(i, values(i), sprintf('%.2f', values(i)), ...
            'HorizontalAlignment', 'center', ...
            'VerticalAlignment', 'bottom');
    end
end


function add_N_separators(T)
% ADD_N_SEPARATORS
% Pridá zvislé čiary medzi skupiny rôznych N.
% HandleVisibility = off zabezpečí, že sa čiary nezobrazia v legende.

    Ns = unique(T.N).';

    for i = 1:numel(Ns)-1
        lastIdx = find(T.N == Ns(i), 1, 'last');

        xline(lastIdx + 0.5, '--', ...
            'Color', [0.5 0.5 0.5], ...
            'HandleVisibility', 'off');
    end
end


function set_N_group_ticks(T)
% SET_N_GROUP_TICKS
% Nastaví x-os podľa skupín N.

    Ns = unique(T.N).';
    tickPositions = zeros(size(Ns));
    tickLabels = strings(size(Ns));

    for i = 1:numel(Ns)
        idx = find(T.N == Ns(i));
        tickPositions(i) = mean(idx);
        tickLabels(i) = "N=" + string(Ns(i));
    end

    xticks(tickPositions);
    xticklabels(tickLabels);
end


function [names, weights] = selected_assets(x, caseType, N, weightTolerance)
% SELECTED_ASSETS
% Názvy a váhy aktív, ktorých váha je aspoň weightTolerance.

    x = x(:);
    x(abs(x) < weightTolerance) = 0;

    idx = find(abs(x) >= weightTolerance);

    names = strings(length(idx), 1);
    weights = strings(length(idx), 1);

    for i = 1:length(idx)
        names(i) = string(get_variable_name(idx(i), char(caseType), N));
        weights(i) = string(fmtWeight4(x(idx(i))));
    end
end


function ok = is_stock_pair_only(names)
% IS_STOCK_PAIR_ONLY
% Overí, či sú vybrané iba x_1 a x_2.

    expected = ["x_1"; "x_2"];
    names = sort(names(:));

    ok = length(names) == 2 && all(names == expected);
end


function textValue = join_or_dash(values)
% JOIN_OR_DASH
% Spojí hodnoty čiarkou alebo vráti pomlčku.

    if isempty(values)
        textValue = "-";
    else
        textValue = strjoin(values, ", ");
    end
end


function value = mean_or_nan(x)
% MEAN_OR_NAN
% Priemer alebo NaN.

    if isempty(x)
        value = NaN;
    else
        value = mean(x, 'omitnan');
    end
end


function textValue = fmtWeight4(value)
% FMTWEIGHT4
% Váha na 4 desatinné miesta.

    textValue = sprintf('%.4f', value);
end


function textValue = fmtPct2(value)
% FMTPCT2
% Percento na 2 desatinné miesta.

    if isnan(value)
        textValue = "NaN";
        return;
    end

    textValue = string(sprintf('%.2f %%', 100 * value));
    textValue = strrep(textValue, '.', ',');
end


function valuesText = fmtPct2Array(values)
% FMTPCT2ARRAY
% Vektorový formát percent na 2 desatinné miesta.

    valuesText = strings(size(values));

    for i = 1:numel(values)
        valuesText(i) = fmtPct2(values(i));
    end
end


function textValue = fmtSci(value)
% FMTSCI
% Formát napr. 1e-8.

    textValue = sprintf('%.10e', value);
    textValue = regexprep(textValue, '(\.\d*?)0+e', '$1e');
    textValue = regexprep(textValue, '\.e', 'e');
    textValue = regexprep(textValue, 'e([+-])0*(\d+)', 'e$1$2');
    textValue = strrep(textValue, 'e+', 'e');
end


function textValue = fmtTheta(value)
% FMTTHETA
% Formát napr. 0.9.

    textValue = sprintf('%.10f', value);
    textValue = regexprep(textValue, '0+$', '');
    textValue = regexprep(textValue, '\.$', '');

    if isempty(textValue)
        textValue = '0';
    end
end